CREATE DATABASE IF NOT EXISTS school_portal CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE school_portal;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  external_id VARCHAR(40) NULL UNIQUE,
  email VARCHAR(190) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role ENUM('ADMIN','FACULTY','STUDENT') NOT NULL,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  status ENUM('ACTIVE','DISABLED') NOT NULL DEFAULT 'ACTIVE',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_users_role_status (role, status)
);

CREATE TABLE IF NOT EXISTS academic_terms (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  academic_year VARCHAR(20) NOT NULL,
  semester ENUM('FIRST','SECOND','SUMMER') NOT NULL,
  is_current BOOLEAN NOT NULL DEFAULT FALSE,
  start_date DATE NULL, end_date DATE NULL,
  UNIQUE KEY uq_term (academic_year, semester)
);
CREATE TABLE IF NOT EXISTS programs (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  code VARCHAR(20) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL, status ENUM('ACTIVE','ARCHIVED') NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE IF NOT EXISTS sections (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  program_id BIGINT UNSIGNED NOT NULL, name VARCHAR(40) NOT NULL, year_level TINYINT UNSIGNED NOT NULL,
  FOREIGN KEY (program_id) REFERENCES programs(id), UNIQUE KEY uq_section (program_id, name, year_level)
);
CREATE TABLE IF NOT EXISTS faculty (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, user_id BIGINT UNSIGNED NOT NULL UNIQUE, faculty_no VARCHAR(40) NOT NULL UNIQUE, position VARCHAR(100) NULL,
  FOREIGN KEY (user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS students (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, user_id BIGINT UNSIGNED NOT NULL UNIQUE, student_no VARCHAR(40) NOT NULL UNIQUE, program_id BIGINT UNSIGNED NULL, section_id BIGINT UNSIGNED NULL,
  FOREIGN KEY (user_id) REFERENCES users(id), FOREIGN KEY (program_id) REFERENCES programs(id), FOREIGN KEY (section_id) REFERENCES sections(id)
);
CREATE TABLE IF NOT EXISTS subjects (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, code VARCHAR(30) NOT NULL UNIQUE, name VARCHAR(180) NOT NULL, units DECIMAL(3,1) NOT NULL, status ENUM('ACTIVE','ARCHIVED') NOT NULL DEFAULT 'ACTIVE'
);
CREATE TABLE IF NOT EXISTS appointments (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, student_id BIGINT UNSIGNED NOT NULL, faculty_id BIGINT UNSIGNED NOT NULL, starts_at DATETIME NOT NULL, ends_at DATETIME NOT NULL,
  status ENUM('PENDING','APPROVED','REJECTED','RESCHEDULED','COMPLETED','CANCELLED') NOT NULL DEFAULT 'PENDING', purpose VARCHAR(500) NOT NULL,
  FOREIGN KEY (student_id) REFERENCES students(id), FOREIGN KEY (faculty_id) REFERENCES faculty(id), INDEX idx_appointments_faculty_time (faculty_id, starts_at)
);
CREATE TABLE IF NOT EXISTS announcements (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, author_id BIGINT UNSIGNED NOT NULL, title VARCHAR(200) NOT NULL, content TEXT NOT NULL,
  priority ENUM('LOW','NORMAL','HIGH') NOT NULL DEFAULT 'NORMAL', status ENUM('DRAFT','PUBLISHED','ARCHIVED') NOT NULL DEFAULT 'DRAFT', published_at DATETIME NULL,
  FOREIGN KEY (author_id) REFERENCES users(id), INDEX idx_announcements_status_date (status, published_at)
);
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT, user_id BIGINT UNSIGNED NULL, action VARCHAR(100) NOT NULL, entity_type VARCHAR(100) NOT NULL, entity_id BIGINT UNSIGNED NULL, metadata JSON NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  FOREIGN KEY (user_id) REFERENCES users(id), INDEX idx_audit_created (created_at)
);
